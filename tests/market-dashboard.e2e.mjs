import { createRequire } from "module";
import http from "http"; import fs from "fs"; import path from "path";
const require = createRequire("/opt/npm-tools/node_modules/");
const { chromium } = require("playwright");
const root = path.resolve(new URL("..", import.meta.url).pathname);
const types = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".json": "application/json" };
const srv = http.createServer((q, r) => { let p = decodeURIComponent(q.url.split("?")[0]); if (p === "/") p = "/index.html"; const f = path.join(root, p); if (!f.startsWith(root) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { r.writeHead(404); return r.end(); } r.writeHead(200, { "content-type": types[path.extname(f)] || "text/plain" }); r.end(fs.readFileSync(f)); });
await new Promise((r) => srv.listen(0, r));
const base = "http://localhost:" + srv.address().port;
const b = await chromium.launch(); let fails = 0;
const ok = (c, m) => { if (!c) { fails++; console.log("FAIL", m); } else console.log("ok  ", m); };
const p = await (await b.newContext({ viewport: { width: 390, height: 800 } })).newPage();
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
await p.goto(base + "/market-performance.html"); await p.waitForSelector(".dash-tile"); await p.waitForTimeout(2800);
ok(await p.locator(".dash-tile").count() === 3 && await p.locator(".dash-card").count() === 3, "overview: three compact tiles and three cards");
ok(await p.locator(".sec-nav-link.active").getAttribute("data-sec") === "overview", "Overview is the first view");
ok((await p.locator(".dash-panel:visible, #section-macro:visible, #section-metals:visible").count()) === 0, "no detail panel shows on the overview");
ok(!(await p.locator(".horizon-toolbar").isVisible()), "return-window bar hidden on the overview");
const tilesText = await p.locator("#dashTiles").innerText();
ok(!/short term|medium term|long term/i.test(tilesText), "no short/medium/long labels");
ok(/Nifty 50/i.test(tilesText) && /Smallcap/i.test(tilesText) && /Gold/i.test(tilesText) && /1 month/i.test(tilesText) && /5 years, per year/i.test(tilesText), "every benchmark shows its horizons");
ok((await p.locator(".dash-table.tops tbody tr").count()) === 8, "four periods each for funds and stocks");
ok(/Sansera/i.test(tilesText) || (await p.locator(".tops-card .pick").count()) === 8, "funds and stocks are in separate cards");
await p.click(".dc-link[data-open=mf]");
ok(await p.locator("#section-mf").isVisible() && !(await p.locator("#dashOverview").isVisible()), "a tile opens its area and hides the overview");
ok(await p.locator("#mfTableBody tr").count() > 3, "fund table rows present");
ok(await p.locator(".horizon-toolbar").isVisible(), "return-window bar appears for a return-based area");
ok(await p.locator(".sec-nav-link.active").getAttribute("data-sec") === "mf", "tab follows the area");
await p.click(".sec-nav-link[data-sec=realestate]");
ok(await p.locator("#section-realestate").isVisible() && !(await p.locator("#section-mf").isVisible()), "one area at a time");
ok(await p.locator("#reAnchorGrid .re-stat-box").count() >= 3, "real estate content intact");
await p.click(".sec-nav-link[data-sec=overview]");
ok(await p.locator("#dashOverview").isVisible(), "Overview tab returns");
await p.goto(base + "/market-performance.html#section-equities"); await p.waitForTimeout(1500);
ok(await p.locator("#section-equities").isVisible(), "a link to #section-equities opens that area");
ok(await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "no sideways scroll on a phone");
ok(errs.length === 0, "no page errors " + errs.join("|"));
await b.close(); srv.close(); process.exit(fails ? 1 : 0);
