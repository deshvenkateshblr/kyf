import { createRequire } from "module";
import http from "http"; import fs from "fs"; import path from "path";
const require = createRequire("/opt/npm-tools/node_modules/");
const { chromium } = require("playwright");
const root = path.resolve(new URL("..", import.meta.url).pathname);
const types = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".json": "application/json" };
const srv = http.createServer((q, r) => { let p = decodeURIComponent(q.url.split("?")[0]); if (p === "/") p = "/index.html"; const f = path.join(root, p); if (!f.startsWith(root) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { r.writeHead(404); return r.end(); } r.writeHead(200, { "content-type": types[path.extname(f)] || "text/plain" }); r.end(fs.readFileSync(f)); });
await new Promise((r) => srv.listen(0, r));
const base = "http://localhost:" + srv.address().port;
const b = await chromium.launch(); let fails = 0;
const ok = (c, m) => { if (!c) { fails++; console.log("FAIL", m); } else console.log("ok  ", m); };
const p = await (await b.newContext({ viewport: { width: 390, height: 800 } })).newPage();
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
await p.goto(base + "/market-performance.html"); await p.waitForSelector(".mk-toggle"); await p.waitForTimeout(1500);
ok(await p.locator(".mk-toggle").count() === 6, "six sections can open and close");
ok(await p.locator(".mk-body:visible").count() === 0, "all start closed");
ok(await p.locator(".mk-summary:visible").count() === 6, "each shows a one-line headline");
ok(!(await p.locator(".horizon-toolbar").isVisible()), "return-window bar hidden while nothing needs it");
await p.click("#section-mf .mk-toggle");
ok(await p.locator("#section-mf .mk-body").isVisible() && !(await p.locator("#section-mf .mk-summary").isVisible()), "opening shows the section, hides its headline");
ok(await p.locator("#mfTableBody tr").count() > 3, "fund table rows present");
ok(await p.locator(".horizon-toolbar").isVisible(), "return-window bar appears with a return-based section");
await p.click("#mkAllBtn");
ok(await p.locator(".mk-body:visible").count() === 6, "Expand all opens everything");
await p.click("#mkAllBtn");
ok(await p.locator(".mk-body:visible").count() === 0, "Collapse all closes everything");
await p.click(".sec-nav-link[data-sec=equities]"); await p.waitForTimeout(300);
ok(await p.locator("#section-equities .mk-body").isVisible(), "a jump link opens its section");
ok(await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "no sideways scroll on a phone");
ok(errs.length === 0, "no page errors " + errs.join("|"));
await b.close(); srv.close(); process.exit(fails ? 1 : 0);
