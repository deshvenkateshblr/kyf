globalThis.window=globalThis; await import("../js/kyf-loan-math.js");
const L=globalThis.KYF_LOAN; let f=0;
const ok=(c,m)=>{console.log((c?"ok  ":"FAIL ")+m); if(!c)f++;};
const near=(a,b,t=1)=>Math.abs(a-b)<=t;
ok(near(L.emi(1000000,9,60),20758.30,1),"EMI of 10 lakh at 9% for 5 years is about 20,758");
ok(L.emi(120000,0,12)===10000,"zero rate divides evenly");
ok(L.emi(0,9,60)===0&&L.emi(1000,9,0)===0,"no loan or no tenure gives 0");
const s=L.schedule({principal:1000000,ratePct:9,months:60,start:new Date(2027,0,1)});
ok(s.months===60&&s.rows[59].balance===0,"60 payments, balance ends at 0");
ok(near(s.totalInterest,s.emi*60-1000000,2),"total interest = payments minus principal");
ok(near(s.rows[0].interest,7500,0.01)&&near(s.rows[0].principal,s.emi-7500,0.02),"first month: interest is balance x rate/12");
ok(near(s.rows.reduce((a,r)=>a+r.principal,0),1000000,1),"principal parts add up to the loan");
ok(s.payoff.getFullYear()===2031&&s.payoff.getMonth()===11,"payoff is December 2031 for a Jan 2027 start");
ok(s.years.length===5&&s.years[0].year===2027&&s.years[4].balance===0,"yearly summary covers 5 calendar years");
const e=L.schedule({principal:1000000,ratePct:9,months:60,extraMonthly:5000,start:new Date(2027,0,1)});
ok(e.months<s.months&&e.totalInterest<s.totalInterest,"an extra payment finishes sooner and costs less interest");
ok(e.rows[e.rows.length-1].balance===0,"and still ends at 0");
const c=L.compare({price:1000000,down:200000,ratePct:9.5,years:5,earnPct:6.8});
ok(c.loan===800000&&near(c.emi,L.emi(800000,9.5,60),0.01),"loan is price minus down payment");
ok(c.winner==="cash"&&c.edge<0,"borrowing at 9.5% while earning 6.8% loses to paying cash");
const c2=L.compare({price:1000000,down:200000,ratePct:7,years:5,earnPct:12});
ok(c2.winner==="loan"&&c2.edge>0,"borrowing at 7% while earning 12% comes out ahead");
const c3=L.compare({price:1000000,down:200000,ratePct:8,years:5,earnPct:8});
ok(near(c3.edge,0,1),"same rate both ways: a wash");
ok(L.compare({price:500000,down:500000,ratePct:9,years:5,earnPct:7}).winner==="cash"&&L.compare({price:500000,down:500000,ratePct:9,years:5,earnPct:7}).emi===0,"all cash: no loan");
ok(near(L.compare({price:1000000,down:200000,ratePct:9.5,years:5,earnPct:6.8,takeHome:100000}).emiShare,c.emi/100000,1e-6),"EMI share of take-home pay");
process.exit(f?1:0);
