import { createRequire } from "module";
import http from "http"; import fs from "fs"; import path from "path";
const require = createRequire("/opt/npm-tools/node_modules/");
const { chromium } = require("playwright");
const root = path.resolve(new URL("..", import.meta.url).pathname);
const types = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".json": "application/json" };
const srv = http.createServer((q, r) => { let p = decodeURIComponent(q.url.split("?")[0]); if (p === "/") p = "/index.html"; const f = path.join(root, p); if (!f.startsWith(root) || !fs.existsSync(f)) { r.writeHead(404); return r.end(); } r.writeHead(200, { "content-type": types[path.extname(f)] || "text/plain" }); r.end(fs.readFileSync(f)); });
await new Promise((r) => srv.listen(0, r));
const base = "http://localhost:" + srv.address().port;
const b = await chromium.launch(); let fails = 0;
const ok = (c, m) => { if (!c) { fails++; console.log("FAIL", m); } else console.log("ok  ", m); };
const p = await (await b.newContext({ viewport: { width: 1200, height: 800 } })).newPage();
await p.goto(base + "/index.html");
ok((await p.textContent("#heroStart")).includes("Get started"), "hero says Get started");
ok(!/plan/i.test(await p.textContent("#heroStart")), "no 'plan' in the button");
await p.click("#heroStart");
await p.waitForSelector("#journeyStrip .jr-step");
ok(await p.locator("#journeyStrip .jr-step.is-here strong").innerText() === "Build your portfolio", "portfolio step is highlighted on portfolio");
await p.click("#journeyStrip .jr-step >> nth=1");
await p.waitForSelector("#journeyStrip .jr-step");
ok(await p.locator("#journeyStrip .jr-step.is-here strong").innerText() === "Name your goals", "highlight moves to Name your goals");
ok(await p.locator("#journeyStrip .jr-step.is-locked a").count() === 0, "step 3 is not a link until it can be used");
await p.goto(base + "/index.html");
ok(await p.locator("#firstTime").isVisible(), "first-time explainer shows for a new visitor");
await p.click("#firstTimeClose");
await p.reload();
ok(!(await p.locator("#firstTime").isVisible()), "explainer stays dismissed");
await b.close(); srv.close(); process.exit(fails ? 1 : 0);
