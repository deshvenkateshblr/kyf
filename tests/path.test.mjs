globalThis.window=globalThis; await import("../data/kyf-path.js"); await import("../js/kyf-path.js");
const P=globalThis.KYF_PATH, D=globalThis.KYF_PATH_DATA; let f=0;
const ok=(c,m)=>{console.log((c?"ok  ":"FAIL ")+m); if(!c)f++;};
const DAY=864e5, now=Date.parse("2026-11-16T00:00:00Z");
const h=(o={})=>Object.assign({id:"h",currentValue:1,allocations:[]},o);
let m=P.build(D,[],{holdings:[],goals:[]},now);
ok(m.pct===0&&m.next.task.id==="p-holdings","empty: 0% and first task is Add what you own");
ok(m.stages.length===4&&m.total===13,"4 stages, 13 tasks when you owe nothing");
m=P.build(D,[],{holdings:[h()],goals:[]},now);
ok(m.stages[0].done===1&&m.next.task.id==="p-debts","holdings auto-tick");
const g={id:"g",baseTargetINR:100,targetYear:2040};
m=P.build(D,[],{holdings:[h({allocations:[{goalId:"g",percentage:100}]})],goals:[g]},now);
ok(["p-goal","p-goals-complete","p-assign"].every(id=>m.stages[1].items.find(i=>i.task.id===id).v.auto),"goal tasks auto-tick");
ok(!P.autoDone("goalsComplete",{goals:[{id:"x",baseTargetINR:0,targetYear:2040}]}),"incomplete goal not complete");
const rec=(id,o)=>[Object.assign({id},o)];
m=P.build(D,rec("house-networth",{status:"done",doneAt:new Date(now-100*DAY).toISOString()}),{holdings:[],goals:[]},now);
let it=m.stages[3].items[0];
ok(it.v.state==="done"&&it.v.renew,"old recurring task is done but due again");
ok(m.renewals.length===1,"renewals listed");
m=P.build(D,rec("p-emergency",{status:"active",snoozedUntil:new Date(now+3*DAY).toISOString()}),{holdings:[],goals:[]},now);
ok(m.stages[1].items[0].v.state==="later"&&m.next.task.id!=="p-emergency","later hides from next");
m=P.build(D,rec("p-debts",{status:"not_applicable"}),{holdings:[],goals:[]},now);
ok(m.stages[0].total===1,"not for me leaves the maths");
const r=P.markDone({id:"a"},now); ok(r.status==="done"&&P.reopen(r).status==="active","mark done / reopen");
ok(Date.parse(P.snooze({id:"a"},now).snoozedUntil)===now+7*DAY,"snooze is a week");
const mg=P.merge([{id:"house-networth",status:"done",doneAt:"x"},{id:"mine",title:"Mine"}],D);
ok(mg.length===15&&mg.find(a=>a.id==="house-networth").status==="done","merge keeps state, adds catalogue, keeps custom");
m=P.build(D,[],{holdings:[h({isLiability:true})],goals:[]},now);
ok(m.stages[0].items.some(i=>i.task.id==="p-highinterest")&&m.total===14,"debt task appears only when you owe something");
ok(P.merge([{id:"p-review",status:"done"}],D).every(a=>a.id!=="p-review"),"retired tasks are dropped");
ok(P.autoDone("emergencyGoal",{goals:[{id:"x",name:"6-Month Buffer"}]}),"emergency goal found by name");
process.exit(f?1:0);
