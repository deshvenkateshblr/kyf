import { createRequire } from "module";
import http from "http"; import fs from "fs"; import path from "path";
const require = createRequire("/opt/npm-tools/node_modules/");
const { chromium } = require("playwright");
const root = path.resolve(new URL("..", import.meta.url).pathname);
const types = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".json": "application/json" };
const srv = http.createServer((q, r) => { let p = decodeURIComponent(q.url.split("?")[0]); if (p === "/") p = "/index.html"; const f = path.join(root, p); if (!f.startsWith(root) || !fs.existsSync(f)) { r.writeHead(404); return r.end(); } r.writeHead(200, { "content-type": types[path.extname(f)] || "text/plain" }); r.end(fs.readFileSync(f)); });
await new Promise((r) => srv.listen(0, r));
const base = "http://localhost:" + srv.address().port;
const b = await chromium.launch(); let fails = 0;
const ok = (c, m) => { if (!c) { fails++; console.log("FAIL", m); } else console.log("ok  ", m); };
const ctx = await b.newContext({ viewport: { width: 390, height: 800 } }); const p = await ctx.newPage();
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
await p.goto(base + "/loans.html");
ok((await p.textContent("#outCompare")).includes("EMI"), "compare renders");
ok(await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "no horizontal scroll (compare)");
const wa = await p.getAttribute("#outCompare a.btn-wa", "href");
ok(wa.startsWith("https://wa.me/?text=") && wa.includes("loans.html"), "whatsapp link");
await p.click("#tab-schedule");
ok(await p.locator("#outSchedule table.sched tbody tr").count() >= 20, "yearly rows");
await p.fill("#sExtra", "5000");
ok((await p.textContent("#outSchedule")).includes("sooner"), "extra payment shows savings");
await p.click("text=By month");
ok(await p.locator("#outSchedule table.sched tbody tr").count() > 100, "monthly rows");
ok(await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "no horizontal scroll (schedule)");
await p.goto(base + "/loans.html?tool=compare&cp=2000000&cd=500000");
ok((await p.inputValue("#cPrice")) === "2000000", "link restores values");
ok(errs.length === 0, "no page errors " + errs.join("|"));
ok(!/<script(?![^>]*src)[^>]*>[^<]/.test(fs.readFileSync(root + "/loans.html", "utf8")), "no inline script");
await b.close(); srv.close(); process.exit(fails ? 1 : 0);
