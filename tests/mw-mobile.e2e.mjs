import { createRequire } from "module";
import http from "http"; import fs from "fs"; import path from "path";
const require = createRequire("/opt/npm-tools/node_modules/");
const { chromium } = require("playwright");
const root = path.resolve(new URL("..", import.meta.url).pathname);
const types = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".json": "application/json" };
const srv = http.createServer((q, r) => { let p = decodeURIComponent(q.url.split("?")[0]); if (p === "/") p = "/index.html"; const f = path.join(root, p); if (!f.startsWith(root) || !fs.existsSync(f)) { r.writeHead(404); return r.end(); } r.writeHead(200, { "content-type": types[path.extname(f)] || "text/plain" }); r.end(fs.readFileSync(f)); });
await new Promise((r) => srv.listen(0, r));
const base = "http://localhost:" + srv.address().port;
const b = await chromium.launch(); let fails = 0;
const ok = (c, m) => { if (!c) { fails++; console.log("FAIL", m); } else console.log("ok  ", m); };
const phone = await (await b.newContext({ viewport: { width: 390, height: 800 } })).newPage();
await phone.goto(base + "/index.html"); await phone.waitForSelector(".mw-card.mw-in", { timeout: 6000 });
const h1 = (await phone.locator(".mw-card").boundingBox()).height;
ok(h1 < 60, "phone card is a slim strip (" + Math.round(h1) + "px)");
await phone.click(".mw-toggle");
const h2 = (await phone.locator(".mw-card").boundingBox()).height;
ok(h2 > 120, "tap opens the full card (" + Math.round(h2) + "px)");
await phone.click(".mw-toggle");
ok((await phone.locator(".mw-card").boundingBox()).height < 60, "shrinks again");
await phone.screenshot({ path: process.env.SHOT || "/tmp/mw.png" });
const desk = await (await b.newContext({ viewport: { width: 1200, height: 800 } })).newPage();
await desk.goto(base + "/index.html"); await desk.waitForSelector(".mw-card.mw-in", { timeout: 6000 });
ok((await desk.locator(".mw-card").boundingBox()).height > 120, "desktop card unchanged");
ok(!(await desk.locator(".mw-toggle").isVisible()), "no toggle on desktop");
await b.close(); srv.close(); process.exit(fails ? 1 : 0);
